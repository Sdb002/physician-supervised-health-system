"""The local readers: a lab report (photo or PDF) -> text lines with boxes.

Photos are read by RapidOCR 3.x, which ships its models (PP-OCRv6 small
detector and recogniser and the text-direction classifier) inside the wheel,
so the first request needs no download. The engine is built once per
process: loading the models takes a second or two, reading a phone photo of
a lab report about 1-1.5 s on a CPU.

PDFs, which most large diagnostic centres send, are read by pypdfium2
(PDFium, the PDF engine of Chrome): a report generated by the lab's system
carries its text, which is taken exactly as printed, with no OCR. A page
with no text (a scan saved as PDF) is rendered and read like a photo.
"""

import importlib.util
import io
import math
from functools import lru_cache

from src.ocr.lab_report import TextLine, upside_down


class OcrEngineUnavailableError(RuntimeError):
    """The local reader's packages are not installed."""


class UnreadableImageError(ValueError):
    """The upload could not be decoded as an image or opened as a PDF."""


ENGINE_NAME = "RapidOCR"
PDF_TEXT_NAME = "PDF text"

PDF_MAX_PAGES = 6
# a scanned page is rendered at 200 dpi, the resolution of a good office
# scan; a text page's points are put on the same scale, so a document mixing
# both has one line height throughout
PDF_RENDER_SCALE = 200 / 72
# fewer characters than this on a page: it is a scan, not text
PDF_MIN_TEXT_CHARS = 20


def local_available() -> bool:
    return all(importlib.util.find_spec(name) is not None for name in ("rapidocr", "onnxruntime"))


def pdf_available() -> bool:
    return importlib.util.find_spec("pypdfium2") is not None


@lru_cache(maxsize=1)
def _engine():
    if not local_available():
        raise OcrEngineUnavailableError(
            "The local lab-slip reader is not installed: pip install rapidocr onnxruntime")
    from rapidocr import RapidOCR

    return RapidOCR()


def _decode(image_bytes: bytes):
    from PIL import Image, ImageOps, UnidentifiedImageError

    try:
        image = Image.open(io.BytesIO(image_bytes))
        # a phone photo is often stored sideways with an EXIF orientation
        # flag; the detector needs the page the way the camera saw it
        image = ImageOps.exif_transpose(image)
        return image.convert("RGB")
    except (UnidentifiedImageError, OSError) as error:
        raise UnreadableImageError("the file could not be read as an image") from error


def _ocr(image) -> list[TextLine]:
    result = _engine()(image)
    if result.txts is None:
        return []
    return [
        TextLine(text=text, score=float(score),
                 box=tuple((float(x), float(y)) for x, y in box))
        for box, text, score in zip(result.boxes, result.txts, result.scores)
    ]


def _sideways(lines: list[TextLine]) -> bool:
    """Whether the page was photographed on its side: most lines of several
    characters come back as boxes taller than they are wide."""
    words = [line for line in lines if len(line.text.strip()) >= 4]
    if not words:
        return False
    tall = sum(1 for line in words
               if math.dist(line.box[0], line.box[3]) > 1.5 * math.dist(line.box[0], line.box[1]))
    return tall > len(words) / 2


def _read_image(image) -> list[TextLine]:
    """RapidOCR's lines for a page image, read with the page the right way up.

    A page photographed on its side (and stored without an EXIF turn) comes
    back as tall boxes; it is turned a quarter and read again. A page upside
    down comes back with each line's text right (the reader's direction
    classifier turns every line) but the layout mirrored, which
    lab_report.upside_down detects; it is turned and read again rather than
    mirrored back, because a short number upside down is ambiguous - "9.9"
    came back as "6.6"."""
    lines = _ocr(image)
    if _sideways(lines):
        image = image.rotate(90, expand=True)
        lines = _ocr(image)
    if upside_down(lines):
        lines = _ocr(image.rotate(180))
    return lines


def read_lines(image_bytes: bytes) -> list[TextLine]:
    """Every text line RapidOCR finds on a photo, with its four-corner box
    and score, the page the right way up."""
    return _read_image(_decode(image_bytes))


def _pdf_text_lines(page) -> list[TextLine]:
    """A PDF page's own text, one line per text run PDFium reports, with its
    box in the render's pixels (y down, as the photo reader's are)."""
    textpage = page.get_textpage()
    _, height = page.get_size()
    lines = []
    for index in range(textpage.count_rects()):
        left, bottom, right, top = textpage.get_rect(index)
        text = textpage.get_text_bounded(left, bottom, right, top).strip()
        if not text:
            continue
        x0, x1 = left * PDF_RENDER_SCALE, right * PDF_RENDER_SCALE
        y0, y1 = (height - top) * PDF_RENDER_SCALE, (height - bottom) * PDF_RENDER_SCALE
        lines.append(TextLine(text=text, score=1.0, box=((x0, y0), (x1, y0), (x1, y1), (x0, y1))))
    return lines


def read_pdf_lines(pdf_bytes: bytes) -> tuple[list[TextLine], int]:
    """The text lines of a PDF's first PDF_MAX_PAGES pages, stacked top to
    bottom as one long page, and how many pages had to be read by OCR."""
    if not pdf_available():
        raise OcrEngineUnavailableError(
            "The PDF reader is not installed on this server: pip install pypdfium2")
    import pypdfium2 as pdfium

    try:
        pdf = pdfium.PdfDocument(pdf_bytes)
    except pdfium.PdfiumError as error:
        raise UnreadableImageError(
            "the PDF could not be opened (is it damaged or password-protected?)") from error
    lines: list[TextLine] = []
    top = 0.0
    scanned = 0
    for index in range(min(len(pdf), PDF_MAX_PAGES)):
        page = pdf[index]
        page_lines = [] if page.get_rotation() else _pdf_text_lines(page)
        if sum(len(line.text) for line in page_lines) >= PDF_MIN_TEXT_CHARS:
            page_height = page.get_size()[1] * PDF_RENDER_SCALE
        else:
            # a scan saved as PDF, or a turned page: read the page as drawn
            image = page.render(scale=PDF_RENDER_SCALE).to_pil().convert("RGB")
            page_lines = _read_image(image)
            page_height = image.height
            scanned += 1
        # pages one below the other, a page's height apart, so the rows of
        # different pages never merge
        lines += [TextLine(line.text, line.score, tuple((x, y + top) for x, y in line.box))
                  for line in page_lines]
        top += page_height
    return lines, scanned
