const TABS = ["overview", "foods", "recipes", "exercise"] as const;
export type ReportTab = (typeof TABS)[number];

function isReportTab(value: string | null | undefined): value is ReportTab {
  return TABS.includes(value as ReportTab);
}

/** A tab's panel. Paper has no tabs, so every panel prints. */
const panel = (on: boolean) =>
  on ? "space-y-9 print:space-y-7" : "hidden print:block print:space-y-7";

function SectionTitle({ children, aside }: { children: React.ReactNode; aside?: React.ReactNode }) {
  return (
    <div className="mb-3 flex flex-wrap items-baseline justify-between gap-x-4 gap-y-1 print:break-after-avoid">
      <h2 className="font-display text-lg font-bold leading-7 text-ink">{children}</h2>
      {aside && <span className="text-sm text-ink-muted">{aside}</span>}
    </div>
  );
}

/** Shared report viewer: the approved plan as a printable prescription sheet. */
export function ReportView({
  visitId,
  viewer,
  initialTab,
}: {
  visitId: string;
  viewer: "doctor" | "patient";
  /** Land directly on a tab, e.g. when linked from the sidebar's Foods/Exercise shortcuts. */
  initialTab?: string;
}) {
  const [lang] = useLang();
  const [useLlm, setUseLlm] = useState(true);
  const [report, setReport] = useState<Report | null>(null);
  const [locked, setLocked] = useState(false);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  const [notes, setNotes] = useState<DoctorNote[]>([]);
  const [addingNote, setAddingNote] = useState(false);
  const [draftNote, setDraftNote] = useState("");
  const [editingNoteId, setEditingNoteId] = useState<number | null>(null);
  const [editDraft, setEditDraft] = useState("");
  const [noteBusy, setNoteBusy] = useState(false);
  const [noteError, setNoteError] = useState<string | null>(null);
  const [tab, setTab] = useState<ReportTab>(isReportTab(initialTab) ? initialTab : "overview");

  // a link to another tab of the same report changes the prop, not the page
  const [linkedTab, setLinkedTab] = useState(initialTab);
  if (initialTab !== linkedTab) {
    setLinkedTab(initialTab);
    if (isReportTab(initialTab)) setTab(initialTab);
  }

  const load = useCallback(() => {
    setLoading(true);
    setError(null);
    api
      .report(visitId, lang, useLlm)
      .then((r) => {
        setReport(r);
        setNotes(r.notes ?? []);
        setLocked(false);
      })
      .catch((e) => {
        if (e instanceof ApiError && e.status === 403) setLocked(true);
        else setError(e.message);
      })
      .finally(() => setLoading(false));
  }, [visitId, lang, useLlm]);

  // fetch on mount and whenever the visit, language or phrasing changes; the
  // loading flag is raised here because nothing else knows a fetch began
  // eslint-disable-next-line react-hooks/set-state-in-effect
  useEffect(load, [load]);

  const submitNote = async () => {
    if (!draftNote.trim()) return;
    setNoteBusy(true);
    setNoteError(null);
    try {
      const created = await api.addNote(visitId, { note: draftNote.trim() });
      setNotes((n) => [...n, created]);
      setDraftNote("");
      setAddingNote(false);
    } catch (err) {
      setNoteError((err as Error).message);
    } finally {
      setNoteBusy(false);
    }
  };

  const startEditNote = (n: DoctorNote) => {
    setEditingNoteId(n.id);
    setEditDraft(n.note);
    setNoteError(null);
  };

  const submitEditNote = async (noteId: number) => {
    if (!editDraft.trim()) return;
    setNoteBusy(true);
    setNoteError(null);
    try {
      const updated = await api.updateNote(visitId, noteId, { note: editDraft.trim() });
      setNotes((n) => n.map((x) => (x.id === noteId ? updated : x)));
      setEditingNoteId(null);
    } catch (err) {
      setNoteError((err as Error).message);
    } finally {
      setNoteBusy(false);
    }
  };

  const t = L[lang];
  const back =
    viewer === "patient"
      ? { href: "/patient/reports", label: t.backPatient }
      : { href: "/doctor/patients", label: t.backDoctor };

  return (
    <div lang={lang} className="mx-auto max-w-5xl space-y-5 print:max-w-none">
      <div className="flex flex-wrap items-center justify-between gap-3 print:hidden">
        <Link
          href={back.href}
          className={`inline-flex items-center gap-1 rounded text-sm font-semibold text-clinical hover:underline ${focusRing}`}
        >
          <IconChevronLeft className="h-4 w-4" />
          {back.label}
        </Link>
        <div className="flex flex-wrap items-center gap-2.5">
          <LangSwitch />
          {viewer === "doctor" && (
            <label className="flex items-center gap-1.5 text-sm text-ink-soft">
              <input
                type="checkbox"
                className={checkboxClass}
                checked={useLlm}
                onChange={(e) => setUseLlm(e.target.checked)}
              />
              {t.aiToggle}
            </label>
          )}
          {report && !locked && (
            <button className={buttonSecondary} onClick={() => window.print()}>
              <IconPrinter className="h-4 w-4" />
              {t.print}
            </button>
          )}
        </div>
      </div>

      {error && <ErrorNote message={error} />}

      {/* an approved plan is never rebuilt: the physician is told when the
          planner has moved on since, and how to plan again */}
      {viewer === "doctor" &&
        report?.engine_version &&
        report.current_engine_version &&
        report.engine_version !== report.current_engine_version && (
          <p
            role="note"
            className="rounded-md border border-watch-line bg-watch-tint px-4 py-2.5 text-sm text-watch-ink print:hidden"
          >
            This plan was built by planner version {report.engine_version}; the current version is{" "}
            {report.current_engine_version} and may plan differently. The plan stays as it was approved. To plan
            again with the current version, record a new visit.
          </p>
        )}

      {locked && (
        <div className="rounded-lg border border-watch-line bg-watch-tint px-6 py-10 text-center">
          <span className="mx-auto flex h-12 w-12 items-center justify-center rounded-full bg-surface text-watch-ink">
            <IconLock className="h-6 w-6" />
          </span>
          <p className="font-display mt-3 text-lg font-bold leading-7 text-ink">{t.lockedTitle}</p>
          <p className="mx-auto mt-1 max-w-md text-ink-soft">
            {viewer === "patient" ? t.lockedPatient : t.lockedDoctor}
          </p>
          {viewer === "doctor" && (
            <Link href="/doctor/review" className={buttonSecondary + " mt-5"}>
              {t.toQueue}
            </Link>
          )}
        </div>
      )}

      {loading && !locked && <Skeleton className="h-144" />}

      {report && !locked && !loading && (() => {
        const r = report.result;
        const anthro = r?.anthropometrics;
        const mealPlan = r?.nutrition?.meal_plan;
        const isWeekPlan = (mealPlan?.days?.length ?? 0) > 0;
        const plan = r?.exercise_plan;
        const edited = Boolean(
          (mealPlan as unknown as { edited_by_physician?: boolean })?.edited_by_physician ||
          (plan as unknown as { edited_by_physician?: boolean })?.edited_by_physician
        );
        const approvedOn = formatDate(report.approved_at, lang);
        // every line the printed sheet sets out as a table, so the letter
        // above them does not print the same lists a second time
        const tabled = [
          ...(mealPlan && !mealPlan.note ? planDays(mealPlan).flatMap((d) => Object.values(d.meals).flat()) : []),
          ...(r?.nutrition?.top_foods ?? []),
          ...(r?.nutrition?.top_recipes ?? []),
          ...Object.values(plan?.type ?? {}).flat(),
        ].flatMap((line) => [line.name_en, line.name_bn ?? ""]);
        // the release statement and the physician's stamp
        const footer = (
          <footer className="flex flex-col gap-6 border-t border-line px-5 py-6 sm:flex-row sm:items-end sm:justify-between sm:px-8 print:mt-7 print:flex-row print:items-end print:justify-between print:px-0 print:pb-2">
            <div className="max-w-xl space-y-1.5 text-xs leading-5 text-ink-muted">
              {(r?.exclusions?.food_tags?.length || r?.exclusions?.exercise_tags?.length) ? (
                <p>{t.safetyNote}</p>
              ) : null}
              <p>{t.disclaimer}</p>
            </div>
            <div className="approval-stamp shrink-0 self-end px-4 py-2 text-center leading-tight print:mr-2">
              <p className="text-base font-bold">{t.stampApproved}</p>
              <p className="text-sm font-semibold">{report.approved_by}</p>
              <p className="text-xs font-semibold">{approvedOn}</p>
            </div>
          </footer>
        );
        return (
          <article className="sheet print:rounded-none">
            {/* letterhead */}
            <header className="sheet-head px-5 pb-5 pt-6 sm:px-8 print:px-0 print:pt-5">
              <div className="flex items-start justify-between gap-4">
                <div className="flex items-center gap-3.5">
                  <IconRx className="h-11 w-11 shrink-0 text-clinical" strokeWidth={2} />
                  <div>
                    <p lang="bn" className="text-lg font-bold leading-tight text-ink">
                      স্বাস্থ্য পরিকল্পনা
                    </p>
                    <p className="text-sm text-ink-muted">{t.brandLine}</p>
                  </div>
                </div>
                <div className="text-right">
                  <p className="text-xs text-ink-muted">{t.visit}</p>
                  <p className="text-xl font-bold text-ink">{report.visit_id}</p>
                </div>
              </div>

              <h1 className="mt-6 text-2xl font-bold text-ink sm:text-[1.75rem] print:mt-4 print:text-2xl">{t.title}</h1>

              {/* Labelled fields: a clinical document is scanned for one value, not read in a line. */}
              <dl className="mt-4 grid grid-cols-2 gap-x-6 gap-y-3 border-t border-line pt-4 sm:grid-cols-4 print:grid-cols-4">
                {[
                  { k: t.patient, v: report.patient_name },
                  { k: t.visitDate, v: report.visit_date ? formatDate(report.visit_date, lang) : "—" },
                  { k: t.approvedBy, v: report.approved_by },
                  { k: t.approvedOn, v: approvedOn },
                ].map((f) => (
                  <div key={f.k}>
                    <dt className="text-xs text-ink-muted">{f.k}</dt>
                    <dd className="mt-0.5 font-semibold text-ink">{f.v}</dd>
                  </div>
                ))}
              </dl>

              {edited && (
                <p className="mt-4">
                  <Badge kind="flag">{t.editedNote}</Badge>
                </p>
              )}
            </header>

            <div className="grid border-t border-line md:grid-cols-[17rem_1fr] print:block">
              {/* findings margin, as on a prescription's left column; on paper a band
                  across the top, so the plan below it has the whole page width:
                  the conditions sit beside the heading and the values in a grid */}
              {anthro && (
                <aside className="border-b border-line bg-surface-soft px-5 py-6 sm:px-8 md:border-b-0 md:border-r md:px-6 print:grid print:break-inside-avoid print:grid-cols-[auto_1fr] print:items-baseline print:gap-x-8 print:border-b print:border-r-0 print:bg-surface print:px-0 print:py-5">
                  <h2 className="text-sm font-semibold text-clinical">{t.measurements}</h2>
                  <div className="mt-4 print:col-span-2 print:row-start-2 print:mt-3 print:grid print:grid-cols-3 print:gap-x-8 print:gap-y-4">
                    <dl className="space-y-4 print:contents print:space-y-0">
                      <div>
                        <dt className="text-sm text-ink-soft">{t.bmiLabel}</dt>
                        <dd className="text-xl font-bold text-ink">
                          {anthro.bmi}
                          <span className="ml-1.5 text-sm font-normal text-ink-muted">
                            {bmiCategoryName(anthro.bmi_category, lang)}
                          </span>
                        </dd>
                      </div>
                      <div>
                        <dt className="text-sm text-ink-soft">{t.energyTarget}</dt>
                        <dd className="text-xl font-bold text-ink">
                          {anthro.target_kcal}
                          <span className="ml-1 text-sm font-normal text-ink-muted">kcal</span>
                        </dd>
                        {viewer === "doctor" && (
                          <dd className="mt-0.5 text-balance text-xs text-ink-muted">
                            {t.restingEnergy} {anthro.ree_kcal}, {t.maintenanceEnergy.toLowerCase()}{" "}
                            {anthro.tdee_kcal}
                          </dd>
                        )}
                      </div>
                    </dl>
                    <div className="mt-5 border-t border-line pt-5 print:contents">
                      {(r?.risk_flags ?? []).length > 0 ? (
                        <FindingsList flags={r.risk_flags} lang={lang} stacked />
                      ) : (
                        <p className="text-sm text-ink-muted">{t.normalAll}</p>
                      )}
                    </div>
                  </div>
                  {(r.conditions ?? []).length > 0 && (
                    <div className="mt-5 border-t border-line pt-4 print:col-start-2 print:row-start-1 print:mt-0 print:flex print:items-baseline print:justify-end print:gap-x-4 print:border-t-0 print:pt-0">
                      <p className="text-sm text-ink-soft">{t.conditions}</p>
                      <ul className="mt-1.5 space-y-0.5 font-semibold text-ink print:mt-0 print:flex print:flex-wrap print:justify-end print:gap-x-5 print:space-y-0">
                        {r.conditions.map((c) => (
                          <li key={c}>{conditionName(c, lang)}</li>
                        ))}
                      </ul>
                    </div>
                  )}
                </aside>
              )}

              <div className="min-w-0">
                <div
                  role="tablist"
                  aria-label={t.title}
                  className="flex gap-1 overflow-x-auto border-b border-line px-3 sm:px-6 print:hidden"
                >
                  {TABS.map((key) => {
                    const on = tab === key;
                    return (
                      <button
                        key={key}
                        role="tab"
                        aria-selected={on}
                        onClick={() => setTab(key)}
                        className={`-mb-px cursor-pointer whitespace-nowrap border-b-2 px-3 py-3.5 text-[15px] transition-colors duration-150 ${focusRing} focus-visible:-outline-offset-2 ${
                          on
                            ? "border-clinical font-semibold text-clinical"
                            : "border-transparent font-medium text-ink-muted hover:text-ink"
                        }`}
                      >
                        {t.tabs[key]}
                      </button>
                    );
                  })}
                </div>

                <div className="space-y-9 px-5 py-6 sm:px-8 print:space-y-7 print:px-0 print:py-5">
                  {/* overview */}
                  <div className={panel(tab === "overview")}>
                    {report.comment && (
                      <div className="rounded-md border-l-4 border-clinical bg-clinical-tint px-4 py-3">
                        <p className="text-sm font-semibold text-clinical">{t.physicianNote}</p>
                        <p className="mt-0.5 text-ink">{report.comment}</p>
                      </div>
                    )}

                    <section className={notes.length === 0 ? "print:hidden" : undefined}>
                      <SectionTitle>{t.doctorNotesTitle}</SectionTitle>
                      {noteError && (
                        <div className="mb-3 print:hidden">
                          <ErrorNote message={noteError} />
                        </div>
                      )}
                      {notes.length === 0 && !addingNote && (
                        <p className="text-sm text-ink-muted">
                          {viewer === "doctor" ? t.noNotesDoctor : t.noNotesPatient}
                        </p>
                      )}
                      <ul className="space-y-3">
                        {notes.map((n) => (
                          <li key={n.id} className="border-l-2 border-line-strong pl-4">
                            {editingNoteId === n.id ? (
                              <div className="space-y-2 print:hidden">
                                <textarea
                                  className={inputClass}
                                  rows={3}
                                  value={editDraft}
                                  onChange={(e) => setEditDraft(e.target.value)}
                                />
                                <div className="flex gap-2">
                                  <button
                                    className={buttonPrimary}
                                    disabled={noteBusy}
                                    onClick={() => submitEditNote(n.id)}
                                  >
                                    {t.saveNote}
                                  </button>
                                  <button
                                    className={buttonSecondary}
                                    disabled={noteBusy}
                                    onClick={() => setEditingNoteId(null)}
                                  >
                                    {t.cancelNote}
                                  </button>
                                </div>
                              </div>
                            ) : (
                              <>
                                <p className="whitespace-pre-wrap text-ink">{n.note}</p>
                                <p className="mt-1 flex items-center justify-between gap-3 text-sm text-ink-muted">
                                  <span>
                                    {n.physician_name}, {formatDate(n.updated_at ?? n.created_at, lang)}
                                    {n.updated_at && ` (${t.editedSuffix})`}
                                  </span>
                                  {viewer === "doctor" && (
                                    <button className={`${linkButton} print:hidden`} onClick={() => startEditNote(n)}>
                                      {t.editNote}
                                    </button>
                                  )}
                                </p>
                              </>
                            )}
                          </li>
                        ))}
                      </ul>
                      {viewer === "doctor" && (
                        <div className="mt-3 print:hidden">
                          {addingNote ? (
                            <div className="space-y-2">
                              <textarea
                                className={inputClass}
                                rows={3}
                                placeholder={t.notePlaceholder}
                                value={draftNote}
                                onChange={(e) => setDraftNote(e.target.value)}
                              />
                              <div className="flex gap-2">
                                <button className={buttonPrimary} disabled={noteBusy} onClick={submitNote}>
                                  {t.saveNote}
                                </button>
                                <button
                                  className={buttonSecondary}
                                  disabled={noteBusy}
                                  onClick={() => {
                                    setAddingNote(false);
                                    setDraftNote("");
                                  }}
                                >
                                  {t.cancelNote}
                                </button>
                              </div>
                            </div>
                          ) : (
                            <button className={linkButton} onClick={() => setAddingNote(true)}>
                              {t.addNote}
                            </button>
                          )}
                        </div>
                      )}
                    </section>

                    <section>
                      <SectionTitle>{t.letter}</SectionTitle>
                      <article className="max-w-prose print:max-w-none">
                        <ReportProse text={report.text} tabled={tabled} />
                      </article>
                      <p className="mt-3 flex items-center gap-1.5 text-xs text-ink-muted print:break-before-avoid">
                        {report.source === "llm" && <IconSparkles className="h-3.5 w-3.5" />}
                        {report.source === "llm" ? t.aiPhrased : t.templatePhrased}
                      </p>
                    </section>
                  </div>

                  {/* meal plan */}
                  <div className={panel(tab === "foods")}>
                    {mealPlan && !mealPlan.note && (
                      <section>
                        <SectionTitle
                          aside={isWeekPlan ? t.weekTarget(mealPlan.target_kcal) : t.mealTarget(mealPlan.target_kcal)}
                        >
                          {isWeekPlan ? t.weekPlan : t.mealPlan}
                        </SectionTitle>
                        <WeekPlan days={planDays(mealPlan)} lang={lang} showItemKcal={viewer === "doctor"} />
                        {mealPlan.totals?.kcal != null && (
                          <p className="mt-2 text-right text-sm text-ink-soft">
                            {isWeekPlan ? t.plannedAverage : t.plannedTotal}{" "}
                            <strong className="text-ink">
                              {Math.round(Number(mealPlan.totals.kcal))} kcal
                            </strong>
                          </p>
                        )}
                        {viewer === "doctor" &&
                          mealPlan.totals?.kcal != null &&
                          mealPlan.target_kcal > 0 &&
                          (() => {
                            const pct = Math.round((Number(mealPlan.totals.kcal) / mealPlan.target_kcal) * 100);
                            if (pct >= 85 && pct <= 115) return null;
                            return (
                              <p className="mt-2 rounded-md border border-watch-line bg-watch-tint px-4 py-2 text-sm text-watch-ink print:hidden">
                                This plan totals {pct}% of the {mealPlan.target_kcal} kcal daily target.
                              </p>
                            );
                          })()}
                      </section>
                    )}
                    {mealPlan && !mealPlan.note && (
                      <PlanNutrition
                        plan={mealPlan}
                        limits={r.nutrition.limits}
                        anthropometrics={anthro}
                        lang={lang}
                        staff={viewer === "doctor"}
                      />
                    )}
                    {(r?.nutrition?.top_foods ?? []).length > 0 && (
                      <section>
                        <SectionTitle>{t.recommendedFoods}</SectionTitle>
                        <RecommendedFoodsList foods={r.nutrition.top_foods} lang={lang} />
                      </section>
                    )}
                  </div>

                  {/* recipes */}
                  <div className={panel(tab === "recipes")}>
                    <section>
                      <SectionTitle>{t.recommendedRecipes}</SectionTitle>
                      {(r?.nutrition?.top_recipes ?? []).length > 0 ? (
                        <>
                          <p className="mb-4 text-sm text-ink-muted print:break-after-avoid">{t.recipesHint}</p>
                          <div className="print:hidden">
                            <RecommendedRecipesList recipes={r.nutrition.top_recipes} lang={lang} />
                          </div>
                          <RecommendedRecipesTable recipes={r.nutrition.top_recipes} lang={lang} />
                        </>
                      ) : (
                        <p className="text-sm text-ink-muted">{t.noRecipes}</p>
                      )}
                    </section>
                  </div>

                  {/* exercise */}
                  <div className={panel(tab === "exercise")}>
                    {/* printed, the stamp stays on the page of the last section
                        instead of risking a final page to itself */}
                    <div className="print:break-inside-avoid">
                      {plan && plan.time && (
                        <section>
                          <SectionTitle>{t.exercise}</SectionTitle>
                          <div className="grid divide-y divide-line rounded-md border border-line sm:grid-cols-3 sm:divide-x sm:divide-y-0 print:grid-cols-3 print:divide-x print:divide-y-0">
                            {(
                              [
                                ["aerobic", t.aerobic, plan.frequency!.aerobic_days],
                                ["strength", t.strength, plan.frequency!.strength_days],
                                ["flexibility", t.flexibility, plan.frequency!.flexibility_days],
                              ] as const
                            ).map(([group, name, days]) => (
                              <div key={group} className="px-4 py-4">
                                <h3 className="font-semibold text-ink">{name}</h3>
                                <p className="text-sm font-semibold text-clinical">{t.perWeek(days)}</p>
                                {group === "aerobic" && (
                                  <p className="text-sm text-ink-soft">
                                    {t.minPerSession(plan.time!.aerobic_min_per_session)}
                                    <br />
                                    {t.targetHr(plan.intensity!.target_hr_bpm[0], plan.intensity!.target_hr_bpm[1])}
                                  </p>
                                )}
                                <ul className="mt-3 space-y-1 text-ink-strong">
                                  {(plan.type?.[group] ?? []).map((ex) => (
                                    <li key={ex.exercise_id}>{localName(ex, lang)}</li>
                                  ))}
                                </ul>
                              </div>
                            ))}
                          </div>
                          {viewer === "doctor" && plan.volume && (
                            <p className="mt-2 text-sm text-ink-muted">
                              {t.weeklyVolume}: ≈{plan.volume.met_min_per_week} MET-min, {plan.volume.est_kcal_per_week} kcal
                            </p>
                          )}
                          {plan.progression && (
                            <p className="mt-3 text-sm text-ink-soft">
                              <strong className="font-semibold text-ink">{t.progression}.</strong> {plan.progression}
                            </p>
                          )}
                        </section>
                      )}
                      <div className="hidden print:block">{footer}</div>
                    </div>
                  </div>
                </div>
              </div>
            </div>

            {/* on paper the footer is set with the exercise plan, above */}
            <div className="print:hidden">{footer}</div>
          </article>
        );
      })()}
    </div>
  );
}
