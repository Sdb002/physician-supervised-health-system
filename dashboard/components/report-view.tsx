const TABS = ["overview", "foods", "exercise"] as const;
export type ReportTab = (typeof TABS)[number];

function isReportTab(value: string | null | undefined): value is ReportTab {
  return TABS.includes(value as ReportTab);
}

const MEAL_ORDER = ["breakfast", "lunch", "dinner", "snack"] as const;

/* Severity reinforcement for the findings table. The badge already carries
 * the status in words - this bar is a second, faster channel, never the only
 * one, so colour is not doing the work alone. */
const TAB_BASE =
  "-mb-px cursor-pointer border-b-2 py-3 text-sm font-medium transition-colors duration-200 " +
  "focus-visible:outline-2 focus-visible:outline-offset-2 focus-visible:outline-clinical ";
const TAB_ON = "border-clinical text-clinical";
const TAB_OFF = "border-transparent text-ink-muted hover:border-line-strong hover:text-ink";

const SEV_BAR_CLASS = "h-4 w-1 shrink-0 rounded-full ";
const SEVERITY_BAR: Record<string, string> = {
  none: "bg-line-strong",
  low: "bg-sky-500",
  moderate: "bg-amber-500",
  high: "bg-orange-500",
  critical: "bg-rose-600",
};

function SectionTitle({ children }: { children: React.ReactNode }) {
  return (
    <h2 className="mb-3 border-b border-line pb-1.5 text-sm font-bold uppercase tracking-wide text-ink-strong">
      {children}
    </h2>
  );
}

/** Shared report viewer: a printable, structured medical report document. */
export function ReportView({
  visitId,
  viewer,
  initialTab,
}: {
  visitId: string;
  viewer: "doctor" | "patient";
  /** Land directly on a tab, e.g. when linked from the sidebar's Foods/Exercise shortcuts. */
  initialTab?: string;
}) {
  const { session } = useAuth();
  const [lang, setLang] = useState<"en" | "bn">("en");
  const [useLlm, setUseLlm] = useState(true);
  const [report, setReport] = useState<Report | null>(null);
  const [locked, setLocked] = useState(false);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  const [notes, setNotes] = useState<DoctorNote[]>([]);
  const [addingNote, setAddingNote] = useState(false);
  const [draftNote, setDraftNote] = useState("");
  const [editingNoteId, setEditingNoteId] = useState<number | null>(null);
  const [editDraft, setEditDraft] = useState("");
  const [noteBusy, setNoteBusy] = useState(false);
  const [noteError, setNoteError] = useState<string | null>(null);
  const [tab, setTab] = useState<ReportTab>(isReportTab(initialTab) ? initialTab : "overview");

  useEffect(() => {
    if (isReportTab(initialTab)) setTab(initialTab);
  }, [initialTab]);

  const load = useCallback(() => {
    setLoading(true);
    setError(null);
    api
      .report(visitId, lang, useLlm)
      .then((r) => {
        setReport(r);
        setNotes(r.notes ?? []);
        setLocked(false);
      })
      .catch((e) => {
        if (e instanceof ApiError && e.status === 403) setLocked(true);
        else setError(e.message);
      })
      .finally(() => setLoading(false));
  }, [visitId, lang, useLlm]);

  useEffect(load, [load]);

  const submitNote = async () => {
    if (!draftNote.trim()) return;
    setNoteBusy(true);
    setNoteError(null);
    try {
      const created = await api.addNote(visitId, { note: draftNote.trim() });
      setNotes((n) => [...n, created]);
      setDraftNote("");
      setAddingNote(false);
    } catch (err) {
      setNoteError((err as Error).message);
    } finally {
      setNoteBusy(false);
    }
  };

  const startEditNote = (n: DoctorNote) => {
    setEditingNoteId(n.id);
    setEditDraft(n.note);
    setNoteError(null);
  };

  const submitEditNote = async (noteId: number) => {
    if (!editDraft.trim()) return;
    setNoteBusy(true);
    setNoteError(null);
    try {
      const updated = await api.updateNote(visitId, noteId, { note: editDraft.trim() });
      setNotes((n) => n.map((x) => (x.id === noteId ? updated : x)));
      setEditingNoteId(null);
    } catch (err) {
      setNoteError((err as Error).message);
    } finally {
      setNoteBusy(false);
    }
  };

  const t = L[lang];

  return (
    <div className="mx-auto max-w-3xl space-y-6">
      <div className="flex flex-wrap items-center justify-between gap-3 print:hidden">
        <h1 className="text-2xl font-bold tracking-tight text-ink">
          {viewer === "patient" ? "My report" : "Patient report"}
        </h1>
        <div className="flex items-center gap-2">
          <div className="flex overflow-hidden rounded-lg border border-line-strong">
            {(["en", "bn"] as const).map((l) => (
              <button
                key={l}
                onClick={() => setLang(l)}
                className={`px-3 py-1.5 text-sm font-medium ${
                  lang === l ? "bg-clinical text-on-clinical" : "bg-surface text-ink-soft hover:bg-surface-soft"
                }`}
              >
                {l === "en" ? "English" : "বাংলা"}
              </button>
            ))}
          </div>
          <label className="flex items-center gap-1.5 text-xs text-ink-muted">
            <input
              type="checkbox"
              className="h-3.5 w-3.5 rounded border-line-strong text-teal-600"
              checked={useLlm}
              onChange={(e) => setUseLlm(e.target.checked)}
            />
            AI phrasing
          </label>
          {report && !locked && (
            <button className={buttonSecondary} onClick={() => window.print()}>
              Print / PDF
            </button>
          )}
        </div>
      </div>

      {error && <ErrorNote message={error} />}

      {locked && (
        <div className="rounded-2xl border border-amber-200 bg-amber-50 p-8 text-center">
          <span className="mx-auto flex h-12 w-12 items-center justify-center rounded-full bg-surface text-amber-600 shadow-sm">
            <IconLock className="h-6 w-6" />
          </span>
          <p className="mt-3 font-semibold text-amber-800">This report is locked</p>
          <p className="mx-auto mt-1 max-w-sm text-sm text-amber-700">
            {viewer === "patient"
              ? "Your physician hasn't approved this visit's assessment yet. The report is released the moment they approve it."
              : "The assessment for this visit has not been approved by a physician. Reports are only released after approval."}
          </p>
          {viewer === "doctor" && (
            <Link href="/doctor/review" className={buttonSecondary + " mt-4"}>
              Go to review queue
            </Link>
          )}
        </div>
      )}

      {loading && !locked && <Skeleton className="h-96" />}

      {report && !locked && !loading && (() => {
        const r = report.result;
        const nameKey = lang === "bn" ? "name_bn" : "name_en";
        const anthro = r?.anthropometrics;
        const mealPlan = r?.nutrition?.meal_plan;
        const plan = r?.exercise_plan;
        const edited = Boolean(
          (mealPlan as unknown as { edited_by_physician?: boolean })?.edited_by_physician ||
          (plan as unknown as { edited_by_physician?: boolean })?.edited_by_physician
        );
        return (
          <div className="overflow-hidden rounded-2xl border border-line bg-surface shadow-sm print:rounded-none print:border-0 print:shadow-none">
            {/* letterhead */}
            <div className="report-head bg-surface-soft px-8 pb-6 pt-7 print:bg-surface">
              <div className="flex items-start justify-between gap-4">
                <div className="flex items-center gap-3">
                  <span className="flex h-11 w-11 items-center justify-center rounded-xl bg-clinical text-on-clinical">
                    <IconHeartPulse className="h-6 w-6" />
                  </span>
                  <div>
                    <p className="text-lg font-bold leading-tight text-ink">স্বাস্থ্য পরিকল্পনা</p>
                    <p className="text-xs text-ink-muted">{t.subtitle}</p>
                  </div>
                </div>
                <span className="rounded-lg border border-line bg-surface px-3 py-1.5 text-right">
                  <span className="block text-[10px] font-semibold uppercase tracking-wider text-ink-muted">
                    {t.visit}
                  </span>
                  <span className="block text-sm font-bold tabular-nums text-ink">
                    #{report.visit_id}
                  </span>
                </span>
              </div>

              <h1 className="mt-6 text-2xl font-bold tracking-tight text-ink">{t.title}</h1>

              {/* Metadata as labelled fields - a clinical document is scanned
                * for a specific value, not read left to right. */}
              <dl className="mt-4 grid grid-cols-2 gap-x-6 gap-y-3 border-t border-line pt-4 sm:grid-cols-4">
                {[
                  { k: t.patient, v: report.patient_name },
                  { k: t.visitDate, v: report.visit_date ? new Date(report.visit_date).toLocaleDateString() : "—" },
                  { k: t.approvedBy, v: report.approved_by },
                  { k: t.approvedOn, v: new Date(report.approved_at).toLocaleDateString() },
                ].map((f) => (
                  <div key={f.k}>
                    <dt className="text-[10px] font-semibold uppercase tracking-wider text-ink-muted">
                      {f.k}
                    </dt>
                    <dd className="mt-0.5 text-sm font-semibold text-ink">{f.v}</dd>
                  </div>
                ))}
              </dl>

              {edited && (
                <p className="mt-3">
                  <Badge kind="moderate">{t.editedNote}</Badge>
                </p>
              )}
            </div>

            <div
              role="tablist"
              aria-label={t.title}
              className="flex gap-6 border-b border-line px-8 print:hidden"
            >
              {TABS.map((key) => {
                const on = tab === key;
                return (
                  <button
                    key={key}
                    role="tab"
                    aria-selected={on}
                    onClick={() => setTab(key)}
                    className={TAB_BASE + (on ? TAB_ON : TAB_OFF)}
                  >
                    {t.tabs[key]}
                  </button>
                );
              })}
            </div>

            <div className="space-y-8 px-8 py-7">
              <div className={tab === "overview" ? "space-y-8" : "hidden print:block print:space-y-8"}>
              {report.comment && (
                <div className="rounded-xl border border-teal-100 bg-teal-50 px-4 py-3 text-sm text-teal-900">
                  <strong>{t.physicianNote}:</strong> {report.comment}
                </div>
              )}

              {/* doctor's notes / recommendations */}
              <section>
                <SectionTitle>{t.doctorNotesTitle}</SectionTitle>
                {noteError && <div className="mb-3 print:hidden"><ErrorNote message={noteError} /></div>}
                {notes.length === 0 && !addingNote && (
                  <p className="text-sm text-ink-muted">
                    {viewer === "doctor" ? t.noNotesDoctor : t.noNotesPatient}
                  </p>
                )}
                <ul className="space-y-3">
                  {notes.map((n) => (
                    <li key={n.id} className="rounded-xl border border-line bg-surface-soft p-3 print:border-line">
                      {editingNoteId === n.id ? (
                        <div className="space-y-2 print:hidden">
                          <textarea
                            className={inputClass}
                            rows={3}
                            value={editDraft}
                            onChange={(e) => setEditDraft(e.target.value)}
                          />
                          <div className="flex gap-2">
                            <button
                              className={buttonPrimary}
                              disabled={noteBusy}
                              onClick={() => submitEditNote(n.id)}
                            >
                              {t.saveNote}
                            </button>
                            <button
                              className={buttonSecondary}
                              disabled={noteBusy}
                              onClick={() => setEditingNoteId(null)}
                            >
                              {t.cancelNote}
                            </button>
                          </div>
                        </div>
                      ) : (
                        <>
                          <p className="whitespace-pre-wrap text-sm text-ink">{n.note}</p>
                          <p className="mt-1.5 flex items-center justify-between text-xs text-ink-muted">
                            <span>
                              {n.physician_name} · {new Date(n.updated_at ?? n.created_at).toLocaleDateString()}
                              {n.updated_at && ` (${t.editedSuffix})`}
                            </span>
                            {viewer === "doctor" && (
                              <button
                                className="font-medium text-teal-700 hover:underline print:hidden"
                                onClick={() => startEditNote(n)}
                              >
                                {t.editNote}
                              </button>
                            )}
                          </p>
                        </>
                      )}
                    </li>
                  ))}
                </ul>
                {viewer === "doctor" && (
                  <div className="mt-3 print:hidden">
                    {addingNote ? (
                      <div className="space-y-2">
                        <textarea
                          className={inputClass}
                          rows={3}
                          placeholder={t.notePlaceholder}
                          value={draftNote}
                          onChange={(e) => setDraftNote(e.target.value)}
                        />
                        <div className="flex gap-2">
                          <button className={buttonPrimary} disabled={noteBusy} onClick={submitNote}>
                            {t.saveNote}
                          </button>
                          <button
                            className={buttonSecondary}
                            disabled={noteBusy}
                            onClick={() => {
                              setAddingNote(false);
                              setDraftNote("");
                            }}
                          >
                            {t.cancelNote}
                          </button>
                        </div>
                      </div>
                    ) : (
                      <button
                        className="text-sm font-medium text-teal-700 hover:underline"
                        onClick={() => setAddingNote(true)}
                      >
                        {t.addNote}
                      </button>
                    )}
                  </div>
                )}
              </section>

              {/* letter / summary */}
              <section>
                <SectionTitle>{t.letter}</SectionTitle>
                <article>
                  <ReportProse text={report.text} />
                </article>
                <p className="mt-2 flex items-center gap-1.5 text-xs text-ink-muted">
                  {report.source === "llm" && <IconSparkles className="h-3.5 w-3.5" />}
                  {report.source === "llm" ? t.aiPhrased : t.templatePhrased}
                </p>
              </section>

              {/* findings */}
              {anthro && (
                <section>
                  <SectionTitle>{t.findings}</SectionTitle>
                  {/* Metric strip: the numbers a physician scans first. */}
                  <div className="mb-5 grid grid-cols-2 gap-px overflow-hidden rounded-xl border border-line bg-line sm:grid-cols-4">
                    {[
                      { label: t.bmiLabel, value: anthro.bmi, unit: anthro.bmi_category },
                      { label: t.energyTarget, value: anthro.target_kcal, unit: "kcal" },
                      { label: t.restingEnergy, value: anthro.ree_kcal, unit: "kcal" },
                      { label: t.maintenanceEnergy, value: anthro.tdee_kcal, unit: "kcal" },
                    ].map((m) => (
                      <div key={m.label} className="bg-surface px-3 py-3">
                        <p className="text-[10px] font-semibold uppercase tracking-wider text-ink-muted">
                          {m.label}
                        </p>
                        <p className="mt-1 text-xl font-bold tabular-nums leading-none text-ink">
                          {m.value}
                        </p>
                        <p className="mt-1 truncate text-xs capitalize text-ink-muted">{m.unit}</p>
                      </div>
                    ))}
                  </div>
                  {(r?.risk_flags ?? []).length > 0 ? (
                    <div className="overflow-hidden rounded-xl border border-line">
                      <table className="w-full text-left text-sm">
                        <thead className="bg-surface-soft text-[10px] uppercase tracking-wider text-ink-muted">
                          <tr>
                            <th scope="col" className="px-3 py-2 font-semibold">{t.biomarker}</th>
                            <th scope="col" className="px-3 py-2 text-right font-semibold">{t.value}</th>
                            <th scope="col" className="px-3 py-2 font-semibold">{t.status}</th>
                          </tr>
                        </thead>
                        <tbody className="divide-y divide-line">
                          {(r?.risk_flags ?? []).map((f) => (
                            <tr key={f.biomarker}>
                              <th
                                scope="row"
                                className="px-3 py-2.5 text-left font-medium capitalize text-ink-strong"
                              >
                                <span className="flex items-center gap-2">
                                  <span
                                    aria-hidden="true"
                                    className={SEV_BAR_CLASS + (SEVERITY_BAR[f.risk] ?? "bg-line")}
                                  />
                                  {f.biomarker.replace(/_/g, " ")}
                                </span>
                              </th>
                              <td className="whitespace-nowrap px-3 py-2.5 text-right font-semibold tabular-nums text-ink">
                                {f.value}
                                <span className="ml-1 text-xs font-normal text-ink-muted">{f.unit}</span>
                              </td>
                              <td className="px-3 py-2.5">
                                <Badge kind={f.risk}>
                                  {f.risk === "none" ? t.allNormal : f.label.replace(/_/g, " ")}
                                </Badge>
                              </td>
                            </tr>
                          ))}
                        </tbody>
                      </table>
                    </div>
                  ) : (
                    <p className="text-sm text-ink-muted">{t.normalAll}</p>
                  )}
                  {(r.conditions ?? []).length > 0 && (
                    <div className="mt-4 flex flex-wrap items-center gap-2 border-t border-line pt-3">
                      <span className="text-[10px] font-semibold uppercase tracking-wider text-ink-muted">
                        {t.conditions}
                      </span>
                      {r.conditions.map((c) => (
                        <Badge key={c} kind="high">
                          {c.replace(/_/g, " ")}
                        </Badge>
                      ))}
                    </div>
                  )}
                </section>
              )}
              </div>

              {/* meal plan */}
              <div className={tab === "foods" ? "space-y-8" : "hidden print:block print:space-y-8"}>
              {mealPlan && !mealPlan.note && (
                <section>
                  <SectionTitle>
                    {t.mealPlan}{" "}
                    <span className="font-medium normal-case text-ink-muted">
                      ({t.mealTarget}: {mealPlan.target_kcal} kcal)
                    </span>
                  </SectionTitle>
                  <div className="grid gap-3 sm:grid-cols-2">
                    {MEAL_ORDER.filter((m) => mealPlan.meals[m]?.length).map((meal) => (
                      <div
                        key={meal}
                        className="overflow-hidden rounded-xl border border-line print:border-line"
                      >
                        <div className="flex items-baseline justify-between border-b border-line bg-surface-soft px-3 py-2">
                          <p className="text-[10px] font-semibold uppercase tracking-wider text-clinical">
                            {t.meals[meal]}
                          </p>
                          <p className="text-xs font-semibold tabular-nums text-ink-muted">
                            {mealPlan.meals[meal].reduce((sum, it) => sum + Number(it.kcal || 0), 0)} kcal
                          </p>
                        </div>
                        <table className="w-full text-sm">
                          <tbody className="divide-y divide-line">
                            {mealPlan.meals[meal].map((it) => (
                              <tr key={it.food_id}>
                                <td className="py-1.5 pl-3 pr-2 text-ink-strong">
                                  {(it as Record<string, string | number>)[nameKey] || it.name_en}
                                </td>
                                <td className="whitespace-nowrap py-1.5 pr-2 text-right tabular-nums text-ink-muted">
                                  {it.qty_g} g
                                </td>
                                <td className="whitespace-nowrap py-1.5 pr-3 text-right text-xs tabular-nums text-ink-muted">
                                  {it.kcal}
                                </td>
                              </tr>
                            ))}
                          </tbody>
                        </table>
                      </div>
                    ))}
                  </div>
                  {mealPlan.totals?.kcal != null && (
                    <p className="mt-2 text-right text-sm text-ink-soft">
                      {t.plannedTotal}:{" "}
                      <strong>{Math.round(Number(mealPlan.totals.kcal))} kcal</strong>
                    </p>
                  )}
                  {viewer === "doctor" &&
                    mealPlan.totals?.kcal != null &&
                    mealPlan.target_kcal > 0 &&
                    (() => {
                      const pct = Math.round(
                        (Number(mealPlan.totals.kcal) / mealPlan.target_kcal) * 100
                      );
                      if (pct >= 85 && pct <= 115) return null;
                      return (
                        <p className="mt-2 rounded-lg border border-amber-200 bg-amber-50 px-4 py-2 text-sm text-amber-800 print:hidden">
                          Note for physician: this plan totals {pct}% of the{" "}
                          {mealPlan.target_kcal} kcal daily target.
                        </p>
                      );
                    })()}
                </section>
              )}
              </div>

              {/* exercise */}
              <div className={tab === "exercise" ? "space-y-8" : "hidden print:block print:space-y-8"}>
              {plan && plan.time && (
                <section>
                  <SectionTitle>{t.exercise}</SectionTitle>
                  <div className="grid gap-3 sm:grid-cols-3">
                    <div className="rounded-xl border border-line bg-surface-soft p-3.5 print:border-line">
                      <p className="text-[10px] font-semibold uppercase tracking-wider text-clinical">
                        {t.aerobic}
                      </p>
                      <p className="mt-1 text-sm text-ink-strong">
                        <strong>{plan.frequency!.aerobic_days}</strong> {t.perWeek} ·{" "}
                        <strong>{plan.time.aerobic_min_per_session}</strong> {t.minPerSession}
                      </p>
                      <p className="mt-0.5 text-xs text-ink-muted">
                        {t.targetHr}: {plan.intensity!.target_hr_bpm[0]}–{plan.intensity!.target_hr_bpm[1]} bpm
                      </p>
                      <ul className="mt-2 space-y-1 text-sm text-ink-soft">
                        {(plan.type?.aerobic ?? []).map((ex) => (
                          <li key={ex.exercise_id} className="flex gap-2">
                            <span aria-hidden="true" className="mt-1.5 h-1 w-1 shrink-0 rounded-full bg-line-strong" />
                            {(ex as Record<string, string | number>)[nameKey] || ex.name_en}
                          </li>
                        ))}
                      </ul>
                    </div>
                    <div className="rounded-xl border border-line bg-surface-soft p-3.5 print:border-line">
                      <p className="text-[10px] font-semibold uppercase tracking-wider text-clinical">
                        {t.strength}
                      </p>
                      <p className="mt-1 text-sm text-ink-strong">
                        <strong>{plan.frequency!.strength_days}</strong> {t.perWeek}
                      </p>
                      <ul className="mt-2 space-y-1 text-sm text-ink-soft">
                        {(plan.type?.strength ?? []).map((ex) => (
                          <li key={ex.exercise_id} className="flex gap-2">
                            <span aria-hidden="true" className="mt-1.5 h-1 w-1 shrink-0 rounded-full bg-line-strong" />
                            {(ex as Record<string, string | number>)[nameKey] || ex.name_en}
                          </li>
                        ))}
                      </ul>
                    </div>
                    <div className="rounded-xl border border-line bg-surface-soft p-3.5 print:border-line">
                      <p className="text-[10px] font-semibold uppercase tracking-wider text-clinical">
                        {t.flexibility}
                      </p>
                      <p className="mt-1 text-sm text-ink-strong">
                        <strong>{plan.frequency!.flexibility_days}</strong> {t.perWeek}
                      </p>
                      <ul className="mt-2 space-y-1 text-sm text-ink-soft">
                        {(plan.type?.flexibility ?? []).map((ex) => (
                          <li key={ex.exercise_id} className="flex gap-2">
                            <span aria-hidden="true" className="mt-1.5 h-1 w-1 shrink-0 rounded-full bg-line-strong" />
                            {(ex as Record<string, string | number>)[nameKey] || ex.name_en}
                          </li>
                        ))}
                      </ul>
                    </div>
                  </div>
                  <p className="mt-2 text-xs text-ink-muted">
                    {t.weeklyVolume}: ≈{plan.volume!.met_min_per_week} MET·min ·{" "}
                    {plan.volume!.est_kcal_per_week} kcal
                  </p>
                  {plan.progression && (
                    <p className="mt-1 text-xs text-ink-muted">
                      {t.progression}: {plan.progression}
                    </p>
                  )}
                </section>
              )}
              </div>

              {/* footer */}
              <div className="border-t border-line pt-4">
                {(r?.exclusions?.food_tags?.length || r?.exclusions?.exercise_tags?.length) ? (
                  <p className="mb-2 text-xs text-ink-muted">{t.safetyNote}</p>
                ) : null}
                <p className="text-xs leading-5 text-ink-muted">{t.disclaimer}</p>
                <div className="mt-6 flex items-end justify-between print:mt-10">
                  <p className="text-xs text-ink-muted">
                    {t.visit} #{report.visit_id} · {new Date(report.approved_at).toLocaleDateString()}
                  </p>
                  <div className="text-center">
                    <p className="w-48 border-t border-line-strong pt-1 text-sm font-medium text-ink-strong">
                      {report.approved_by}
                    </p>
                    <p className="text-xs text-ink-muted">{t.approvedBy}</p>
                  </div>
                </div>
              </div>
            </div>
          </div>
        );
      })()}
    </div>
  );
}
